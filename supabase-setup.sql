-- 1) The gifts table -------------------------------------------------
create table if not exists public.gifts (
  id          bigint generated by default as identity primary key,
  name        text    not null check (char_length(name) between 1 and 80),
  description text    not null default '' check (char_length(description) <= 300),
  category    text    not null default 'Other' check (char_length(category) between 1 and 40),
  points      integer not null check (points between 0 and 100000),
  stock       integer not null default 0 check (stock between 0 and 100000),
  image       text,
  hidden      boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- The original photo kept with each gift (so it can be re-edited or used as it is later).
alter table public.gifts add column if not exists original_image text;

-- Discount in percent (0 = no discount). Price after discount = points x (100 - discount) / 100, rounded.
alter table public.gifts add column if not exists discount integer not null default 0 check (discount between 0 and 90);

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists gifts_touch on public.gifts;
create trigger gifts_touch before update on public.gifts
for each row execute function public.touch_updated_at();

-- 2) Who is an admin -------------------------------------------------
-- Only user ids listed here can change gifts or photos.
-- Nobody can read or change this list through the website.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.admins enable row level security;
revoke all on public.admins from anon, authenticated;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- 3) Row level security: the "locks" on the gifts table --------------
alter table public.gifts enable row level security;

drop policy if exists "Everyone sees visible gifts; admin sees all" on public.gifts;
create policy "Everyone sees visible gifts; admin sees all" on public.gifts
  for select to anon, authenticated
  using (not hidden or (select public.is_admin()));

drop policy if exists "Admin adds gifts" on public.gifts;
create policy "Admin adds gifts" on public.gifts
  for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "Admin edits gifts" on public.gifts;
create policy "Admin edits gifts" on public.gifts
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Admin deletes gifts" on public.gifts;
create policy "Admin deletes gifts" on public.gifts
  for delete to authenticated using ((select public.is_admin()));

-- 4) Explicit grants (Supabase no longer adds these automatically) ---
grant usage on schema public to anon, authenticated;
grant select on public.gifts to anon, authenticated;
grant insert, update, delete on public.gifts to authenticated;

-- 5) Photo storage ----------------------------------------------------
-- A public "gift-photos" folder: anyone can view photos, only the admin
-- can upload, replace or delete them. Max 3 MB, images only.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('gift-photos', 'gift-photos', true, 3145728,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admin reads gift photos" on storage.objects;
create policy "Admin reads gift photos" on storage.objects
  for select to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin uploads gift photos" on storage.objects;
create policy "Admin uploads gift photos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin replaces gift photos" on storage.objects;
create policy "Admin replaces gift photos" on storage.objects
  for update to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()))
  with check (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin deletes gift photos" on storage.objects;
create policy "Admin deletes gift photos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()));

-- 6) Requests the girls confirmed they SENT on WhatsApp ---------------
-- Saved only after the girl taps "Yes, I sent it". Names only, never phone numbers.
-- Only the admin can read them. The shop can only add one, through submit_request(),
-- which looks up the real gift names and prices itself.
alter table public.gifts add column if not exists original_image text;

create table if not exists public.requests (
  id           bigint generated by default as identity primary key,
  ref          text    not null unique check (ref ~ '^DS-[A-Z0-9]{6}$'),
  name         text    not null check (char_length(name) between 2 and 40),
  items        jsonb   not null,
  total_gifts  integer not null,
  total_points integer not null,
  status       text    not null default 'new' check (status in ('new', 'done', 'cancelled')),
  created_at   timestamptz not null default now(),
  done_at      timestamptz
);
alter table public.requests enable row level security;
revoke all on public.requests from anon, authenticated;
grant select, update, delete on public.requests to authenticated;

drop policy if exists "Admin reads requests" on public.requests;
create policy "Admin reads requests" on public.requests
  for select to authenticated using ((select public.is_admin()));
drop policy if exists "Admin updates requests" on public.requests;
create policy "Admin updates requests" on public.requests
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Admin deletes requests" on public.requests;
create policy "Admin deletes requests" on public.requests
  for delete to authenticated using ((select public.is_admin()));

create or replace function public.submit_request(p_ref text, p_name text, p_items jsonb)
returns text language plpgsql security definer set search_path = '' as $$
declare
  v_items jsonb := '[]'::jsonb; v_gifts int := 0; v_points int := 0;
  it jsonb; g record; q int; v_price int;
begin
  p_name := btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
  if char_length(p_name) < 2 or char_length(p_name) > 40 then raise exception 'Please enter your name'; end if;
  if coalesce(p_ref, '') !~ '^DS-[A-Z0-9]{6}$' then raise exception 'Bad order number'; end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'Your cart is empty';
  end if;
  if (select count(*) from public.requests where created_at > now() - interval '10 minutes') >= 40 then
    raise exception 'Too many requests right now, please try again in a few minutes';
  end if;
  for it in select value from jsonb_array_elements(p_items) loop
    q := least(greatest(coalesce((it->>'qty')::int, 0), 0), 100);
    if q < 1 then continue; end if;
    select id, name, points, discount into g from public.gifts where id = (it->>'id')::bigint and not hidden;
    if not found then continue; end if;
    v_price := round(g.points * (100 - g.discount) / 100.0)::int;   -- price after discount
    v_items := v_items || jsonb_build_array(jsonb_build_object('id', g.id, 'name', g.name, 'qty', q, 'points', v_price, 'was', g.points));
    v_gifts := v_gifts + q; v_points := v_points + q * v_price;
  end loop;
  if v_gifts = 0 then raise exception 'Your cart is empty'; end if;
  insert into public.requests (ref, name, items, total_gifts, total_points)
  values (p_ref, p_name, v_items, v_gifts, v_points)
  on conflict (ref) do nothing;
  return p_ref;
end $$;
revoke all on function public.submit_request(text, text, jsonb) from public;
grant execute on function public.submit_request(text, text, jsonb) to anon, authenticated;

-- Admin: "Done" lowers the stock of the requested gifts (never below 0). "Undo" puts it back.
create or replace function public.complete_request(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare r record; it jsonb;
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  select * into r from public.requests where id = p_id for update;
  if not found or r.status <> 'new' then return; end if;
  for it in select value from jsonb_array_elements(r.items) loop
    update public.gifts set stock = greatest(0, stock - (it->>'qty')::int) where id = (it->>'id')::bigint;
  end loop;
  update public.requests set status = 'done', done_at = now() where id = p_id;
end $$;

create or replace function public.reopen_request(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare r record; it jsonb;
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  select * into r from public.requests where id = p_id for update;
  if not found then return; end if;
  if r.status = 'done' then
    for it in select value from jsonb_array_elements(r.items) loop
      update public.gifts set stock = stock + (it->>'qty')::int where id = (it->>'id')::bigint;
    end loop;
  end if;
  update public.requests set status = 'new', done_at = null where id = p_id;
end $$;
revoke all on function public.complete_request(bigint) from public;
revoke all on function public.reopen_request(bigint) from public;
grant execute on function public.complete_request(bigint) to authenticated;
grant execute on function public.reopen_request(bigint) to authenticated;

-- 7) Shop settings: the message at the bottom of the shop ---------------
