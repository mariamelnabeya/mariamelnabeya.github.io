-- 1) The gifts table -------------------------------------------------
create table if not exists public.gifts (
  id          bigint generated by default as identity primary key,
  name        text    not null check (char_length(name) between 1 and 80),
  description text    not null default '' check (char_length(description) <= 300),
  category    text    not null default 'Other' check (char_length(category) between 1 and 40),
  points      integer not null check (points between 0 and 100000),
  stock       integer not null default 0 check (stock between 0 and 100000),
  image       text,
  hidden      boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists gifts_touch on public.gifts;
create trigger gifts_touch before update on public.gifts
for each row execute function public.touch_updated_at();

-- 2) Who is an admin -------------------------------------------------
-- Only user ids listed here can change gifts or photos.
-- Nobody can read or change this list through the website.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.admins enable row level security;
revoke all on public.admins from anon, authenticated;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- 3) Row level security: the "locks" on the gifts table --------------
alter table public.gifts enable row level security;

drop policy if exists "Everyone sees visible gifts; admin sees all" on public.gifts;
create policy "Everyone sees visible gifts; admin sees all" on public.gifts
  for select to anon, authenticated
  using (not hidden or (select public.is_admin()));

drop policy if exists "Admin adds gifts" on public.gifts;
create policy "Admin adds gifts" on public.gifts
  for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "Admin edits gifts" on public.gifts;
create policy "Admin edits gifts" on public.gifts
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Admin deletes gifts" on public.gifts;
create policy "Admin deletes gifts" on public.gifts
  for delete to authenticated using ((select public.is_admin()));

-- 4) Explicit grants (Supabase no longer adds these automatically) ---
grant usage on schema public to anon, authenticated;
grant select on public.gifts to anon, authenticated;
grant insert, update, delete on public.gifts to authenticated;

-- 5) Photo storage ----------------------------------------------------
-- A public "gift-photos" folder: anyone can view photos, only the admin
-- can upload, replace or delete them. Max 3 MB, images only.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('gift-photos', 'gift-photos', true, 3145728,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admin reads gift photos" on storage.objects;
create policy "Admin reads gift photos" on storage.objects
  for select to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin uploads gift photos" on storage.objects;
create policy "Admin uploads gift photos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin replaces gift photos" on storage.objects;
create policy "Admin replaces gift photos" on storage.objects
  for update to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()))
  with check (bucket_id = 'gift-photos' and (select public.is_admin()));

drop policy if exists "Admin deletes gift photos" on storage.objects;
create policy "Admin deletes gift photos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'gift-photos' and (select public.is_admin()));

